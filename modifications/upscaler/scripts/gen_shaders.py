"""Compile shaders/*.vert|frag to SPIR-V and write src/shaders_spv.h.

Needs glslangValidator (apt: glslang-tools). The generated header is committed so
the Android build does not need it.
"""
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADERS = [('kFullscreenVert', 'fullscreen.vert'), ('kSgsr1Frag', 'sgsr1.frag')]


def compile_spirv(source, output):
    subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0', '-o', str(output), str(source)],
                   check=True, capture_output=True, text=True)


def main():
    lines = [
        '// SPDX-License-Identifier: MIT',
        '// Copyright (c) 2026 XHYN-PH',
        '// Generated by scripts/gen_shaders.py from shaders/. Do not edit.',
        '// sgsr1.frag is derived from Snapdragon GSR (BSD-3-Clause, Qualcomm Innovation Center, Inc.).',
        '#pragma once',
        '#include <cstdint>',
        '',
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for name, filename in SHADERS:
            out = pathlib.Path(tmp) / (filename + '.spv')
            try:
                compile_spirv(ROOT / 'shaders' / filename, out)
            except subprocess.CalledProcessError as error:
                sys.exit(error.stdout + error.stderr)
            data = out.read_bytes()
            assert len(data) % 4 == 0
            words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
            lines.append('static const uint32_t %s[] = {' % name)
            for i in range(0, len(words), 8):
                lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
            lines.append('};')
            lines.append('')
    (ROOT / 'src' / 'shaders_spv.h').write_text('\n'.join(lines))
    print('wrote src/shaders_spv.h')


if __name__ == '__main__':
    main()
